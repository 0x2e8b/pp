#!/usr/bin/env python3
"""Generate extraction profiles from a Sycope instance's alert definitions.

    SYCOPE_URL=https://sycope SYCOPE_USER=admin SYCOPE_PASS=... \
        python tools/profiles/gen_profiles.py [--all] [--table] [--macros] \
            [-o profiles.json] [--macros-out macros.yaml]

Stdlib only. Reads `GET /npm/api/v1/alert-defs` (read-only) and writes the profiles built by
sycope_recorder.profiles. With --macros it also reads every `$MACRO$` the definitions use
(`GET /npm/api/v1/pipeline/macro/<name>`): readable ones are expanded before the filters are
derived (a macro like `$DNS$` can carry a port or protocol), unreadable ones are reported and
listed in the profile notes; none of this stops the run. `--macros-out` writes a YAML report of
what was read (and why not), for the installer log and for lab tooling.

The JSON (-o profiles.json) holds the editable fields with a help block on top; the descriptive
fields read from Sycope (shape, throttling, interval, macros, notes) go to profiles.info.json next to it.

Run it at install/update time, not per alert. TLS verification is off by default (Sycope ships a
self-signed certificate); pass --verify to enable it.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "src"))
from sycope_recorder.profiles import build_profiles, dumps, dumps_info, info_path  # noqa: E402
from sycope_recorder.sycope_import import Sycope, SycopeError, read_macros  # noqa: E402


def macros_yaml(macros: dict[str, dict], source: str) -> str:
    """A small YAML report (JSON scalars are valid YAML, so no YAML library is needed)."""
    lines = [f"# Generated by tools/profiles/gen_profiles.py from {source} at "
             f"{time.strftime('%Y-%m-%d %H:%M:%S')}", "macros:"]
    for name, m in macros.items():
        lines += [f"  {name}:", f"    status: {json.dumps(m['status'])}", f"    nql: {json.dumps(m['nql'])}"]
        if m["lookups"]:
            lines.append("    lookups:")
            for lk in m["lookups"]:
                lines += [f"      - lookup: {json.dumps(lk['lookup'])}",
                          f"        field: {json.dumps(lk['field'])}",
                          f"        values: {json.dumps(lk['values'])}",
                          f"        status: {json.dumps(lk['status'])}",
                          f"        networks: {json.dumps(lk['networks'])}"]
    return "\n".join(lines) + "\n"


def table(profiles: list[dict]) -> str:
    rows = [("name", "stream", "shape", "range", "key", "notes")]
    for p in profiles:
        rows.append((
            (p["name"] or "")[:40], p["stream"] or "?", p["shape"],
            f'{p["time_range_s"] // 60}m', ",".join(p["alert_key"]), "; ".join(p["notes"]),
        ))
    widths = [max(len(r[i]) for r in rows) for i in range(5)]
    return "\n".join(
        "  ".join(c.ljust(w) for c, w in zip(r, widths)) + "  " + r[5] for r in rows
    )


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--all", action="store_true", help="include inactive definitions/templates")
    ap.add_argument("--table", action="store_true", help="print a readable table instead of JSON")
    ap.add_argument("--macros", action="store_true", help="read and expand the $MACRO$s")
    ap.add_argument("--macros-out", help="write a YAML report of the macros read (implies --macros)")
    ap.add_argument("--verify", action="store_true", help="verify the TLS certificate")
    ap.add_argument("-o", "--output", help="write JSON here instead of stdout")
    args = ap.parse_args()
    try:
        base = os.environ["SYCOPE_URL"].rstrip("/")
        user, password = os.environ["SYCOPE_USER"], os.environ["SYCOPE_PASS"]
    except KeyError as exc:
        raise SystemExit(f"set {exc.args[0]} (SYCOPE_URL, SYCOPE_USER, SYCOPE_PASS)")
    try:
        client = Sycope(base, user, password, args.verify)
    except SycopeError as exc:
        raise SystemExit(str(exc))
    defs = client.alert_defs()
    macros = None
    if args.macros or args.macros_out:
        read = read_macros(client, defs)
        macros = {n: m["nql"] for n, m in read.items()}
        ok = sum(1 for t in macros.values() if t)
        print(f"macros: {ok} of {len(read)} readable"
              + ("" if ok == len(read) else
                 " (unreadable: " + ", ".join(f"{n}={m['status']}" for n, m in read.items() if not m["nql"]) + ")"),
              file=sys.stderr)
        for n, m in read.items():
            for lk in m["lookups"]:
                print(f"  ${n}$ -> lookup {lk['lookup']!r} {lk['field']}={lk['values']}: "
                      f"{len(lk['networks'])} network(s) [{lk['status']}]", file=sys.stderr)
        if args.macros_out:
            with open(args.macros_out, "w") as fh:
                fh.write(macros_yaml(read, base))
    profiles = build_profiles(defs, not args.all, macros)
    text = table(profiles) + "\n" if args.table else dumps(profiles)
    if args.output:
        with open(args.output, "w") as fh:
            fh.write(dumps(profiles) if args.output.endswith(".json") else text)
        if args.output.endswith(".json"):
            with open(info_path(args.output), "w") as fh:
                fh.write(dumps_info(profiles))
        print(f"{len(profiles)} profiles -> {args.output}"
              + (f" (+ {info_path(args.output)})" if args.output.endswith(".json") else ""), file=sys.stderr)
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
